// Creates the team login details Excel file with placeholder values on the R drive
// (network share, VPN only) at \\192.168.2.25\Common\QA\Katalon-Data\LoginDetails.xlsx.
// It is used for a profile that has no "credentialsfile" in profiles/<name>.json (and when
// ELCOM_CREDENTIALS_FILE is not set in .env).
// Open the file afterwards and replace the placeholders with the real login details.
// Never overwrites an existing file.
// Run: npm run create-login-file
require('dotenv').config({ path: require('path').join(__dirname, '..', '.env') });
const fs = require('fs');
const path = require('path');
const ExcelJS = require('exceljs');
const { DEFAULT_CREDENTIALS_FILE, NEW_USER_SHEET, CREDENTIAL_COLUMNS } = require('../src/helpers');

(async () => {
  const file = DEFAULT_CREDENTIALS_FILE;
  if (fs.existsSync(file)) {
    console.log(`Already exists, not changed: ${file}`);
    return;
  }
  if (!fs.existsSync(path.dirname(file))) {
    console.error(`Folder not reachable: ${path.dirname(file)}\nConnect to the VPN and try again.`);
    process.exit(1);
  }
  const profiles = fs.readdirSync(path.join(__dirname, '..', 'profiles'))
    .filter((f) => f.endsWith('.json'))
    .map((f) => path.basename(f, '.json'));

  const workbook = new ExcelJS.Workbook();
  // First sheet: the login used by every test. Second sheet: the user TC9757 creates.
  for (const name of ['Login Details', NEW_USER_SHEET]) {
    const sheet = workbook.addWorksheet(name);
    sheet.columns = CREDENTIAL_COLUMNS.map((header) => ({ header, key: header, width: 28 }));
    sheet.getRow(1).font = { bold: true };
    for (const Profile of profiles) {
      sheet.addRow({
        Profile,
        Username: 'ENTER_USERNAME',
        Password: 'ENTER_ENCRYPTED_PASSWORD (npm run encrypt-password)',
        TOTPSecret: '',
      });
    }
  }
  const notes = workbook.addWorksheet('Notes');
  notes.getColumn(1).width = 110;
  [
    'Login details for the Elcom upgrade suite (Playwright).',
    'One row per profile (the file names in the profiles folder). The row matching PROFILE is used; "default" when PROFILE is not set.',
    'Sheet "Login Details": the login used by every test. Sheet "Add new user with group": username and password of the user TC9757 - Add New User with group creates.',
    'Username and Password are required in both sheets. Passwords must be the ENC:v1:... text from npm run encrypt-password. TOTPSecret is only needed if the site asks for MFA.',
    'Keep this file on the R drive only - do not copy it to your machine, the project folder, OneDrive or email.',
    'This workbook was generated by a script written with an AI tool.',
  ].forEach((line) => notes.addRow([line]));

  await workbook.xlsx.writeFile(file);
  console.log(`Created: ${file}`);
  console.log(`Rows for profiles: ${profiles.join(', ')}`);
  console.log('Open it and, in both sheets, enter the username and paste the output of npm run encrypt-password as the password.');
})();
