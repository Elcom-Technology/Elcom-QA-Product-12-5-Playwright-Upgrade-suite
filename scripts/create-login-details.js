// Creates a local login details Excel file with placeholder values at
// C:\Users\<you>\ElcomAutomation\LoginDetails.xlsx. It is only used for a profile that has no
// "credentialsfile" in profiles/<name>.json (and when ELCOM_CREDENTIALS_FILE is not set in .env).
// Open the file afterwards and replace the placeholders with the real login details.
// Never overwrites an existing file.
// Run: npm run create-login-file
require('dotenv').config({ path: require('path').join(__dirname, '..', '.env') });
const fs = require('fs');
const path = require('path');
const ExcelJS = require('exceljs');
const { LOCAL_CREDENTIALS_FILE, CREDENTIAL_COLUMNS } = require('../src/helpers');

(async () => {
  if (fs.existsSync(LOCAL_CREDENTIALS_FILE)) {
    console.log(`Already exists, not changed: ${LOCAL_CREDENTIALS_FILE}`);
    return;
  }
  const profiles = fs.readdirSync(path.join(__dirname, '..', 'profiles'))
    .filter((f) => f.endsWith('.json'))
    .map((f) => path.basename(f, '.json'));

  const workbook = new ExcelJS.Workbook();
  const sheet = workbook.addWorksheet('Login Details');
  sheet.columns = CREDENTIAL_COLUMNS.map((header) => ({ header, key: header, width: 28 }));
  sheet.getRow(1).font = { bold: true };
  for (const Profile of profiles) {
    sheet.addRow({
      Profile,
      Username: 'ENTER_USERNAME',
      Password: 'ENTER_ENCRYPTED_PASSWORD (npm run encrypt-password)',
      TOTPSecret: '',
      NewUserPassword: '',
    });
  }
  const notes = workbook.addWorksheet('Notes');
  notes.getColumn(1).width = 110;
  [
    'Login details for the Elcom upgrade suite (Playwright).',
    'One row per profile (the file names in the profiles folder). The row matching PROFILE is used; "default" when PROFILE is not set.',
    'Username and Password are required. Password must be the ENC:v1:... text from npm run encrypt-password. TOTPSecret is only needed if the site asks for MFA. NewUserPassword is used by TC9757 - Add New User with group.',
    'Keep this file on this machine only - do not copy it into the project folder, OneDrive or email.',
    'This workbook was generated by a script written with an AI tool.',
  ].forEach((line) => notes.addRow([line]));

  fs.mkdirSync(path.dirname(LOCAL_CREDENTIALS_FILE), { recursive: true });
  await workbook.xlsx.writeFile(LOCAL_CREDENTIALS_FILE);
  console.log(`Created: ${LOCAL_CREDENTIALS_FILE}`);
  console.log(`Rows for profiles: ${profiles.join(', ')}`);
  console.log('Open it, enter the username, and paste the output of npm run encrypt-password as the password.');
})();
